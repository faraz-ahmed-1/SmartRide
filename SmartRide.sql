CREATE TABLE Wallet(
  WalletID INT AUTO_INCREMENT PRIMARY KEY,
  UserID INT NOT NULL,
  Balance DECIMAL(10,2) DEFAULT 0,
  UpdatedTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (UserID) REFERENCES Users(ID)
);
